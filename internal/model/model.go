type Role string

const (
	RoleViewer        Role = "viewer"
	RoleDriver        Role = "driver"
	RoleDispatcher    Role = "dispatcher"
	RoleAdministrator Role = "administrator"
)

func (r Role) Valid() bool {
	switch r {
	case RoleViewer, RoleDriver, RoleDispatcher, RoleAdministrator:
		return true
	default:
		return false
	}
}

