func (k TurnoutKind) Valid() bool {
	switch k {
	case TurnoutKindSimple, TurnoutKindThreeWay, TurnoutKindDoubleSlip, TurnoutKindSingleSlip, TurnoutKindCustom:
		return true
	default:
		return false
	}
}

